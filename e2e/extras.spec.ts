import { expect, test } from '@playwright/test'

// E11-2 (R157–R159): register extras, sell them with a reservation, add and remove after the sale.
test('extras: register, sell with the reservation, change after the sale', async ({ page }) => {
  await page.goto('/cadastro')
  await page.getByLabel('Seu nome').fill('Pessoa extras')
  await page.getByLabel('Nome da agência').fill('Agência extras')
  await page.getByLabel('E-mail', { exact: true }).fill(`e2e-extras-${Date.now()}-${Math.random().toString(36).slice(2, 8)}@teste.dev`)
  await page.getByLabel('Senha', { exact: true }).fill('senha1234')
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Criar conta' }).click()
  await expect(page).toHaveURL('/')

  await page.goto('/clientes/novo')
  await page.getByLabel('Nome', { exact: true }).fill('Ana Extras')
  await page.getByRole('button', { name: 'Salvar cliente' }).click()
  await expect(page.getByRole('heading', { name: 'Ana Extras' })).toBeVisible()

  await page.goto('/passeios/novo')
  await page.getByLabel('Nome do passeio').fill('Praia com extras')
  await page.getByRole('button', { name: 'Salvar passeio' }).click()
  await expect(page.getByRole('heading', { name: 'Praia com extras', level: 1 })).toBeVisible()
  await page.getByLabel('Data da saída').fill('2030-03-10')
  await page.getByLabel('Vagas (capacidade)').fill('10')
  await page.getByLabel('Preço por pessoa (R$)').fill('100,00')
  await page.getByRole('button', { name: 'Criar saída' }).click()
  await expect(page.getByText('Saída criada.')).toBeVisible()
  await page.getByRole('link', { name: /10\/03\/2030/ }).click()
  await expect(page.getByRole('heading', { name: 'Saída de 10/03/2030' })).toBeVisible()
  const urlSaida = page.url()

  // Register two extras (the owner sees the cost)
  await page.getByRole('link', { name: 'Extras', exact: true }).first().click()
  await expect(page.getByRole('heading', { name: 'Extras', level: 1 })).toBeVisible()
  await page.getByRole('button', { name: 'Cadastrar extra' }).click()
  await expect(page.getByText('Digite o nome do extra.')).toBeVisible()
  await page.getByLabel('Nome do extra').fill('Almoço')
  await page.getByLabel('Preço de venda (R$)').fill('40,00')
  await page.getByLabel('Custo (R$, opcional)').fill('25,00')
  await page.getByRole('button', { name: 'Cadastrar extra' }).click()
  await expect(page.getByText('Extra cadastrado.')).toBeVisible()
  await page.getByLabel('Nome do extra').fill('Fotos')
  await page.getByLabel('Preço de venda (R$)').fill('15,00')
  await page.getByLabel('Como cobrar').selectOption('por_reserva')
  await page.getByRole('button', { name: 'Cadastrar extra' }).click()
  await expect(page.getByRole('table', { name: 'Extras' })).toContainText('R$ 25,00')

  // Sell: 2 people + 2 lunches + photos = 295,00
  await page.goto(urlSaida)
  await page.getByLabel(/Buscar cliente/).fill('ana')
  await page.getByRole('button', { name: 'Buscar' }).click()
  await page.getByRole('link', { name: /Ana Extras/ }).click()
  await page.getByLabel('Número de pessoas').fill('2')
  await page.getByRole('button', { name: 'Incluir 2 Almoço' }).click()
  await page.getByLabel(/Fotos/).fill('1')
  await expect(page.getByText('Total: R$ 295,00')).toBeVisible()
  await page.getByRole('button', { name: 'Reservar' }).click()
  await expect(page.getByText('Reserva feita.')).toBeVisible()
  await expect(page.getByRole('listitem').filter({ hasText: 'Ana Extras' })).toContainText('R$ 295,00')

  // The reservation shows the extras; remove the photos, add them back
  await page.getByRole('listitem').filter({ hasText: 'Ana Extras' }).getByRole('link', { name: 'Pagamentos e detalhes' }).click()
  await expect(page.getByRole('heading', { name: /Reserva de/ })).toBeVisible()
  await expect(page.getByText('2 × Almoço')).toBeVisible()
  await page.getByRole('button', { name: 'Remover Fotos' }).click()
  await page.getByRole('button', { name: 'Remover mesmo' }).click()
  await expect(page.getByText('1 × Fotos')).toHaveCount(0)
  await expect(page.getByText('R$ 280,00').first()).toBeVisible()
  await page.getByLabel('Extra', { exact: true }).selectOption({ label: 'Fotos · R$ 15,00 por reserva' })
  await page.getByLabel('Quantidade').fill('1')
  await page.getByRole('button', { name: 'Incluir extra' }).click()
  await expect(page.getByText('Extra incluído e total atualizado.')).toBeVisible()
  await expect(page.getByText('R$ 295,00').first()).toBeVisible()
})
