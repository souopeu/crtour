import { expect, test } from '@playwright/test'

const iso = (dias: number) => new Date(Date.now() + dias * 86_400_000 - 3 * 3_600_000).toISOString().slice(0, 10) // Brazil day (UTC-3)
const br = (data: string) => data.split('-').reverse().join('/')
const PDF = { name: 'recibo.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\n% recibo de teste\n%%EOF\n') }

// E10-2 (R149–R150): commission paid in parts until settled, and payments to a supplier in one batch with a receipt.
test('comissão paga e repasse em lote com comprovante', async ({ page }) => {
  await page.goto('/cadastro')
  await page.getByLabel('Seu nome').fill('Pessoa repasses')
  await page.getByLabel('Nome da agência').fill('Agência repasses')
  await page.getByLabel('E-mail', { exact: true }).fill(`e2e-repasses-${Date.now()}-${Math.random().toString(36).slice(2, 8)}@teste.dev`)
  await page.getByLabel('Senha', { exact: true }).fill('senha1234')
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Criar conta' }).click()
  await expect(page).toHaveURL('/')

  // Commission rule: 5% for the owner, who sells a R$ 2.000,00 reservation and receives it in full
  await page.goto('/configuracoes')
  const regra = page.getByRole('region', { name: 'Comissão' })
  await regra.getByLabel(/% por vendedor/).check()
  await regra.getByRole('button', { name: 'Salvar regra' }).click()
  await expect(regra.getByText('Regra salva.')).toBeVisible()
  const pessoas = regra.getByRole('group', { name: 'Percentual de cada pessoa' })
  await pessoas.getByLabel('Pessoa repasses').fill('5')
  await pessoas.getByRole('button', { name: 'Salvar' }).click()
  await expect(pessoas.getByText('Salvo.')).toBeVisible()

  await page.goto('/fornecedores')
  await page.getByLabel('Nome').fill('Viação Sol')
  await page.getByRole('button', { name: 'Cadastrar fornecedor' }).click()
  await expect(page.getByRole('table', { name: 'Fornecedores' })).toContainText('Viação Sol')

  await page.goto('/clientes/novo')
  await page.getByLabel('Nome', { exact: true }).fill('Ana Repasse')
  await page.getByRole('button', { name: 'Salvar cliente' }).click()
  await expect(page.getByRole('heading', { name: 'Ana Repasse' })).toBeVisible()
  await page.goto('/passeios/novo')
  await page.getByLabel('Nome do passeio').fill('Serra')
  await page.getByRole('button', { name: 'Salvar passeio' }).click()
  await expect(page.getByRole('heading', { name: 'Serra', level: 1 })).toBeVisible()
  await page.getByLabel('Data da saída').fill(iso(10))
  await page.getByLabel('Vagas (capacidade)').fill('10')
  await page.getByLabel('Preço por pessoa (R$)').fill('1.000,00')
  await page.getByRole('button', { name: 'Criar saída' }).click()
  await page.getByRole('link', { name: new RegExp(br(iso(10)).replace(/\//g, '\\/')) }).click()
  await expect(page.getByRole('heading', { name: `Saída de ${br(iso(10))}` })).toBeVisible()
  const urlSaida = page.url()
  await page.getByLabel(/Buscar cliente/).fill('ana')
  await page.getByRole('button', { name: 'Buscar' }).click()
  await page.getByRole('link', { name: /Ana Repasse/ }).click()
  await page.getByLabel('Número de pessoas').fill('2')
  await page.getByRole('button', { name: 'Reservar' }).click()
  await expect(page.getByText('Reserva feita.')).toBeVisible()
  await page.getByRole('listitem').filter({ hasText: 'Ana Repasse' }).filter({ visible: true }).getByRole('link', { name: 'Pagamentos e detalhes' }).click()
  await page.getByLabel('Valor (R$)', { exact: true }).fill('2.000,00')
  await page.getByRole('button', { name: 'Registrar pagamento' }).click()
  await expect(page.getByText('Reserva quitada: não há saldo a receber.')).toBeVisible()

  // A cost of the departure for the supplier
  await page.goto(urlSaida)
  const custo = page.getByRole('region', { name: 'Custos e margem' }).getByRole('form', { name: 'Novo custo' })
  await custo.getByLabel('Descrição').fill('Ônibus')
  await custo.getByLabel('Valor do custo (R$)').fill('800,00')
  await custo.getByLabel('Fornecedor (opcional)').selectOption({ label: 'Viação Sol' })
  await custo.getByRole('button', { name: 'Adicionar custo' }).click()
  await expect(page.getByText('Custo registrado.')).toBeVisible()

  // An agency bill for the same supplier
  await page.goto('/financeiro/contas')
  await page.getByText('+ Nova conta a pagar').click()
  const nova = page.getByRole('form', { name: 'Lançar conta' })
  await nova.getByLabel('Descrição').fill('Revisão do ônibus')
  await nova.getByLabel('Fornecedor (opcional)').selectOption({ label: 'Viação Sol' })
  await nova.getByLabel('Valor (R$)').fill('200,00')
  await nova.getByRole('button', { name: 'Lançar conta' }).click()
  await expect(page.getByText('Conta lançada.')).toBeVisible()

  // Commission: due R$ 100,00; pay 60 now, then the rest
  await page.goto('/comissoes')
  const acerto = page.getByRole('table', { name: 'Pagamento das comissões' })
  await expect(acerto.getByRole('row', { name: /Pessoa repasses/ })).toContainText('R$ 100,00')
  await acerto.getByRole('button', { name: 'Registrar pagamento' }).click()
  const pagarCom = page.getByRole('form', { name: 'Pagamento da comissão de Pessoa repasses' })
  await expect(pagarCom.getByLabel('Valor (R$)')).toHaveValue('100,00')
  await pagarCom.getByLabel('Valor (R$)').fill('60,00')
  await pagarCom.getByRole('button', { name: 'Confirmar pagamento' }).click()
  await expect(acerto.getByRole('row', { name: /Pessoa repasses/ })).toContainText('R$ 40,00')
  await acerto.getByRole('button', { name: 'Registrar pagamento' }).click()
  await page.getByRole('form', { name: 'Pagamento da comissão de Pessoa repasses' }).getByRole('button', { name: 'Confirmar pagamento' }).click()
  await expect(acerto.getByRole('row', { name: /Pessoa repasses/ })).toContainText('Em dia')
  await expect(page.getByRole('list', { name: 'Pagamentos feitos' }).getByRole('listitem')).toHaveCount(2)

  // Repasses: the supplier groups the cost and the bill; pay both at once with a receipt
  await page.getByRole('navigation', { name: 'Comissões ou repasses' }).getByRole('link', { name: 'Repasses a fornecedores' }).click()
  const lote = page.getByRole('form', { name: 'Pagar fornecedores' })
  await expect(lote.getByRole('group', { name: /Viação Sol/ })).toContainText('R$ 1.000,00')
  await lote.getByRole('checkbox', { name: 'Viação Sol' }).check()
  await expect(lote.getByText('2 lançamentos marcados · R$ 1.000,00')).toBeVisible()
  await lote.getByLabel(/Comprovante/).setInputFiles(PDF)
  await lote.getByRole('button', { name: 'Pagar selecionados' }).click()
  await expect(page.getByText('2 lançamentos pagos.')).toBeVisible()
  await expect(page.getByText('Nada a pagar a fornecedores.')).toBeVisible()

  // The bill now shows as paid, with the receipt behind a private link
  await page.goto('/financeiro/contas?filtro=pagas')
  await page.getByRole('table', { name: 'Contas a pagar' }).getByRole('link', { name: 'Revisão do ônibus' }).click()
  const link = page.getByRole('link', { name: 'Ver comprovante' })
  await expect(link).toBeVisible()
  const resposta = await page.request.get((await link.getAttribute('href'))!)
  expect(resposta.status()).toBe(200)
})
