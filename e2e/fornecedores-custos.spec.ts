import { expect, test } from '@playwright/test'

const iso = (dias: number) => new Date(Date.now() + dias * 86_400_000 - 3 * 3_600_000).toISOString().slice(0, 10) // Brazil day

test('suppliers, costs per departure, margin on the departure and on the panel', async ({ page }) => {
  await page.goto('/cadastro')
  await page.getByLabel('Seu nome').fill('Pessoa custos')
  await page.getByLabel('Nome da agência').fill('Agência custos')
  await page.getByLabel('E-mail', { exact: true }).fill(`e2e-custos-${Date.now()}@teste.dev`)
  await page.getByLabel('Senha', { exact: true }).fill('senha1234')
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Criar conta' }).click()
  await expect(page).toHaveURL('/')

  await page.goto('/clientes/novo')
  await page.getByLabel('Nome', { exact: true }).fill('Ana Souza')
  await page.getByRole('button', { name: 'Salvar cliente' }).click()
  await expect(page.getByRole('heading', { name: 'Ana Souza' })).toBeVisible()
  await page.goto('/passeios/novo')
  await page.getByLabel('Nome do passeio').fill('Serra')
  await page.getByRole('button', { name: 'Salvar passeio' }).click()
  await expect(page.getByRole('heading', { name: 'Serra', level: 1 })).toBeVisible()
  await page.getByLabel('Data da saída').fill(iso(0)) // this month, for the panel
  await page.getByLabel('Vagas (capacidade)').fill('10')
  await page.getByLabel('Preço por pessoa (R$)').fill('1.000,00')
  await page.getByRole('button', { name: 'Criar saída' }).click()
  await page.getByRole('link', { name: new RegExp(iso(0).split('-').reverse().join('/')) }).click()
  await expect(page.getByRole('heading', { name: /Saída de/ })).toBeVisible()
  const urlSaida = page.url()
  await page.getByLabel(/Buscar cliente/).fill('ana')
  await page.getByRole('button', { name: 'Buscar' }).click()
  await page.getByRole('link', { name: /Ana Souza/ }).click()
  await page.getByLabel('Número de pessoas').fill('2')
  await page.getByRole('button', { name: 'Reservar' }).click()
  await expect(page.getByText('Reserva feita.')).toBeVisible()

  // Suppliers
  await page.goto('/passeios')
  await page.getByRole('link', { name: 'Fornecedores' }).click()
  await expect(page.getByText(/Nenhum fornecedor ainda/)).toBeVisible()
  const novo = page.getByRole('form', { name: 'Novo fornecedor' })
  await novo.getByRole('button', { name: 'Cadastrar fornecedor' }).click()
  await expect(novo.getByText('Digite o nome do fornecedor.')).toBeVisible()
  await novo.getByLabel('Nome').fill('Van do Zé')
  await novo.getByLabel('Tipo').selectOption({ label: 'Transporte' })
  await novo.getByLabel('Contato (opcional)').fill('(11) 98888-0000')
  await novo.getByRole('button', { name: 'Cadastrar fornecedor' }).click()
  await expect(page.getByText('Fornecedor cadastrado.')).toBeVisible()
  await expect(page.getByRole('list', { name: 'Fornecedores' })).toContainText('Van do Zé · Transporte')

  // Costs and margin on the departure
  await page.goto(urlSaida)
  const custos = page.getByRole('region', { name: 'Custos e margem' })
  await expect(custos.getByText('Vendido').locator('..')).toContainText('R$ 2.000,00')
  await expect(custos.getByText('Margem', { exact: true }).locator('..')).toContainText('R$ 2.000,00 (100%)')
  const form = custos.getByRole('form', { name: 'Novo custo' })
  await form.getByRole('button', { name: 'Adicionar custo' }).click()
  await expect(form.getByText('Descreva o custo (ex.: ônibus, guia, hotel).')).toBeVisible()
  await form.getByLabel('Descrição').fill('Ônibus')
  await form.getByLabel('Valor do custo (R$)').fill('800,00')
  await form.getByLabel('Fornecedor (opcional)').selectOption({ label: 'Van do Zé' })
  await form.getByLabel('Vencimento (opcional)').fill(iso(5))
  await form.getByRole('button', { name: 'Adicionar custo' }).click()
  await expect(custos.getByText('Custo registrado.')).toBeVisible()
  await form.getByLabel('Descrição').fill('Guia')
  await form.getByLabel('Valor do custo (R$)').fill('200,00')
  await form.getByLabel('Já foi pago').check()
  await form.getByLabel('Data do pagamento').fill(iso(0))
  await form.getByRole('button', { name: 'Adicionar custo' }).click()
  await expect(custos.getByRole('list', { name: 'Custos da saída' }).getByRole('listitem')).toHaveCount(2)
  await expect(custos.getByText('Custos', { exact: true }).locator('..')).toContainText('R$ 1.000,00')
  await expect(custos.getByText('Margem', { exact: true }).locator('..')).toContainText('R$ 1.000,00 (50%)')
  await expect(custos.getByText('Custos a pagar').locator('..')).toContainText('R$ 800,00')
  await expect(custos.getByRole('listitem').filter({ hasText: 'Ônibus' })).toContainText('Van do Zé')

  await custos.getByRole('listitem').filter({ hasText: 'Ônibus' }).getByRole('button', { name: 'Marcar como pago hoje' }).click()
  await expect(custos.getByText('Custos a pagar').locator('..')).toContainText('R$ 0,00')

  // R53: the panel shows the month's margin
  await page.goto('/painel')
  await expect(page.getByText(/^Margem das saídas de/).locator('..')).toContainText('R$ 1.000,00')
  await expect(page.getByText(/^Margem das saídas de/).locator('..')).toContainText('1 saída · vendido R$ 2.000,00 · custos R$ 1.000,00')

  // Deleting the supplier keeps its cost (without supplier)
  await page.goto('/fornecedores')
  await page.getByRole('button', { name: 'Apagar Van do Zé' }).click()
  await page.getByRole('button', { name: 'Apagar mesmo' }).click()
  await expect(page.getByText(/Nenhum fornecedor ainda/)).toBeVisible()
  await page.goto(urlSaida)
  await expect(custos.getByRole('listitem').filter({ hasText: 'Ônibus' })).not.toContainText('Van do Zé')
  await custos.getByRole('button', { name: 'Apagar custo Guia' }).click()
  await custos.getByRole('button', { name: 'Apagar mesmo' }).click()
  await expect(custos.getByText('Custos', { exact: true }).locator('..')).toContainText('R$ 800,00')
})
